import React, {useCallback,useEffect,useState} from "react";
import {api,errMsg} from "../../lib/api";
import {CandleChart} from "./FourChartTerminal";

// Shared candle view: identical market-data origin as KAOS bot's chart terminal.
// It never invents a price, triggers an order, or substitutes a crypto
// chart for unsupported forex/equity providers.
export default function PaperMarketChart({symbol,assetClass="CRYPTO_SPOT",onQuote}) {
  const [seconds,setSeconds]=useState(60);
  const [state,setState]=useState({candles:[],source:null,fetched_at:null});
  const [error,setError]=useState("");
  const [loading,setLoading]=useState(false);
  const market=symbol?.trim()?.toUpperCase() || "";
  const load=useCallback(async()=>{
    if(assetClass!=="CRYPTO_SPOT" || !/^[A-Z0-9]{2,10}-[A-Z]{3,5}$/.test(market)){
      setState({candles:[],source:null});setError("Market chart unavailable: no verified data feed for this market.");
      return;
    }
    setLoading(true);
    try{
      const r=await api.get("/api/v1/paper/candles/"+encodeURIComponent(market),{params:{granularity:seconds}});
      if(!Array.isArray(r.data?.candles))throw Error("Invalid candle payload");
      setState(r.data);setError("");
    }catch(e){setError(errMsg(e)||"Market data unavailable");setState({candles:[],source:null});}
    finally{setLoading(false);}
  },[assetClass,market,seconds]);
  useEffect(()=>{load();const id=setInterval(()=>{if(!document.hidden)load();},15000);return()=>clearInterval(id);},[load]);
  return <section className="card-surface p-5 space-y-3" data-testid="kaos-paper-market-chart">
    <div className="flex flex-wrap items-center justify-between gap-3">
      <div><h3 className="font-heading font-semibold text-[#D4AF37]">{market||"Select a market"} · Market chart</h3>
        <p className="text-xs text-slate-400">Completed provider candles · read-only market data</p></div>
      <div className="flex items-center gap-2">
        <select aria-label="Paper chart timeframe" className="rounded border border-[#48402E] bg-[#111] p-2 text-sm" value={seconds} onChange={e=>setSeconds(Number(e.target.value))}>
          <option value={60}>1 minute</option><option value={300}>5 minutes</option><option value={900}>15 minutes</option>
        </select>
        <button type="button" onClick={load} className="rounded border border-[#D4AF37] p-2 text-xs text-[#D4AF37]">Refresh</button>
      </div>
    </div>
    {error?<p role="status" className="text-sm text-amber-300">{error}</p>:<CandleChart candles={state.candles}/>}
    <p className="text-xs text-slate-500">{loading?"Updating · ":""}Source: {state.source||"Unavailable"} · {state.candles?.length||0} completed candles · neither AI signals nor orders are generated by this chart.</p>
  </section>;
}
