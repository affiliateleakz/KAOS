import React, { useEffect, useState } from "react";
import { useParams, Link, useSearchParams } from "react-router-dom";
import { api } from "../lib/api";
import { Brand, RiskBar } from "../components/Brand";
import { Button } from "../components/ui/button";

const BACKEND = process.env.REACT_APP_BACKEND_URL;

export default function SharePage() {
  const { id } = useParams();
  const [sp] = useSearchParams();
  const ref = sp.get("ref");
  const [d, setD] = useState(undefined);
  const imgUrl = `${BACKEND}/api/share/${id}/image.png`;

  useEffect(() => {
    api.get(`/api/share/${id}`).then((r) => setD(r.data)).catch(() => setD(null));
  }, [id]);

  useEffect(() => {
    // Referral attribution: remember the sharer's code and count the click.
    if (ref) {
      try { localStorage.setItem("kaos_ref", ref); } catch (e) {}
      api.get(`/api/aff/track?ref=${encodeURIComponent(ref)}&campaign=signal_share`).catch(() => {});
    }
  }, [ref]);

  useEffect(() => {
    // Best-effort social meta tags for crawlers that execute JS.
    const set = (p, c) => {
      let el = document.querySelector(`meta[property="${p}"]`) || document.querySelector(`meta[name="${p}"]`);
      if (!el) { el = document.createElement("meta"); el.setAttribute("property", p); document.head.appendChild(el); }
      el.setAttribute("content", c);
    };
    if (d) {
      const t = `KAOS ${d.engine} · ${d.direction} — Trade With KAOS`;
      document.title = t;
      set("og:title", t);
      set("og:description", d.reason || "A deterministic KAOS Strategy signal.");
      set("og:image", imgUrl);
      set("twitter:card", "summary_large_image");
      set("twitter:image", imgUrl);
    }
  }, [d, imgUrl]);

  return (
    <div className="flex min-h-screen flex-col bg-[#080808] text-white">
      <div className="glass-nav px-6 py-4"><Brand /></div>
      <div className="flex flex-1 items-center justify-center px-4 py-12">
        <div className="w-full max-w-2xl" data-testid="share-page">
          {d === undefined && <p className="text-center text-slate-500">Loading…</p>}
          {d === null && <p className="text-center text-slate-500" data-testid="share-not-found">This signal link has expired or does not exist.</p>}
          {d && (
            <div className="card-surface p-6">
              <img src={imgUrl} alt={`KAOS ${d.engine} ${d.direction}`} data-testid="share-image"
                className="w-full rounded-md border border-[#2E2E2E]" />
              <div className="mt-6 flex flex-wrap items-center gap-x-6 gap-y-2">
                <span className="font-heading text-2xl font-bold text-[#D4AF37]">{d.engine}</span>
                <span className={`font-mono text-lg font-bold ${d.direction === "BUY" ? "text-[#22C55E]" : "text-[#C62828]"}`}>{d.direction}</span>
                <span className="font-mono text-sm text-slate-400">expiry {d.expiration} · confidence {d.confidence}</span>
              </div>
              {d.reason && <p className="mt-2 text-sm text-slate-400">{d.reason}</p>}
              <div className="mt-6 flex flex-wrap items-center gap-3">
                <Link to={ref ? `/register?ref=${encodeURIComponent(ref)}` : "/register"}><Button data-testid="share-cta" className="bg-[#22C55E] text-black font-semibold">Get Access to KAOS</Button></Link>
                <Link to="/" className="text-sm text-slate-400 hover:text-white">Learn more</Link>
              </div>
              <p className="mt-4 font-mono text-[10px] text-slate-500">Signal preview generated by the deterministic KAOS engine · not financial advice.</p>
            </div>
          )}
        </div>
      </div>
      <RiskBar />
    </div>
  );
}
